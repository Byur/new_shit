import React from 'react';
import {COUNTRIES, LAND, WINDOW, WORLD_H, WORLD_W} from '../geo';
import {theme} from '../theme';

/**
 * The world, Pacific-centred.
 *
 * This is the second view of the same subject. The section (Section.tsx) shows
 * the *mechanism* — where the warm water sits and where the rain therefore
 * falls. This shows the *consequence*: that the rainfall anomaly lands on a
 * planet that is already divided into supply regions, and that a handful of
 * those regions carry most of a given commodity.
 *
 * The window is a deliberate cut through the mid-Atlantic at 25°W, which is the
 * only ocean-only meridian that puts the Pacific in the middle of the frame.
 * Coastlines are Natural Earth 1:110m, generated by scripts/build-geo.mjs into
 * ../geo.ts. The projection is equirectangular, so a straight horizontal line
 * on screen is a line of constant latitude.
 */

export const MAP = {left: 120, top: 196, width: 1680, height: Math.round((1680 * WORLD_H) / WORLD_W)};
const SCALE = MAP.width / WORLD_W;

/** Longitude in the source data (-180..180) into the window's own range. */
const windowLon = (lon: number): number => (lon < WINDOW.lon0 ? lon + 360 : lon);

export const project = (lon: number, lat: number): {x: number; y: number} => {
  const wx = ((windowLon(lon) - WINDOW.lon0) / (WINDOW.lon1 - WINDOW.lon0)) * WORLD_W;
  const wy = ((WINDOW.lat1 - lat) / (WINDOW.lat1 - WINDOW.lat0)) * WORLD_H;
  return {x: MAP.left + wx * SCALE, y: MAP.top + wy * SCALE};
};

export type Anomaly = {
  lon: number;
  lat: number;
  /** radius in degrees of longitude / latitude */
  rx: number;
  ry: number;
  /** 0..1; defaults to 1 */
  intensity?: number;
  kind: 'wet' | 'dry';
  label?: string;
  reveal?: number;
};

export type Marker = {
  lon: number;
  lat: number;
  label?: string;
  sub?: string;
  color: string;
  reveal?: number;
  /** draws a short leader up-right so a label doesn't sit on the coastline */
  side?: 'left' | 'right' | 'up' | 'down';
  /** which side of the dot the text sits on; use 'left' near the right edge */
  labelSide?: 'left' | 'right';
};

const OCEAN_LABELS: Array<{lon: number; lat: number; text: string; size: number}> = [
  {lon: 170, lat: 12, text: '太 平 洋', size: 44},
  {lon: 78, lat: -22, text: '印 度 洋', size: 32},
  {lon: -12, lat: 24, text: '大 西 洋', size: 26},
];

const CONTINENT_LABELS: Array<{lon: number; lat: number; text: string; size: number}> = [
  {lon: 134, lat: -25, text: '澳大利亚', size: 19},
  {lon: 108, lat: -2, text: '印尼', size: 18},
  {lon: 22, lat: -22, text: '非洲南部', size: 18},
  {lon: 42, lat: 8, text: '非洲之角', size: 17},
  {lon: 78, lat: 22, text: '印度', size: 19},
  {lon: -58, lat: -12, text: '巴西', size: 20},
  {lon: -64, lat: -36, text: '阿根廷', size: 17},
  {lon: -76, lat: -10, text: '秘鲁', size: 18},
  {lon: -80, lat: 9, text: '巴拿马', size: 16},
  {lon: -100, lat: 38, text: '北美洲', size: 20},
  {lon: 104, lat: 34, text: '中国', size: 19},
];

export const WorldMap: React.FC<{
  opacity?: number;
  /** 0..1 how much of the base map has been drawn */
  baseReveal?: number;
  anomalies?: Anomaly[];
  markers?: Marker[];
  /** ISO numeric codes to lift out of the landmass */
  highlight?: Array<{iso: string; color: string; reveal: number}>;
  equatorReveal?: number;
  /** label the Pacific's east-west extent */
  spanReveal?: number;
  dim?: number;
  showContinentLabels?: boolean;
}> = ({
  opacity = 1,
  baseReveal = 1,
  anomalies = [],
  markers = [],
  highlight = [],
  equatorReveal = 0,
  spanReveal = 0,
  dim = 0,
  showContinentLabels = true,
}) => {
  if (opacity <= 0.01) return null;

  const equatorY = project(0, 0).y;
  const pngWest = project(99.5, 0).x;
  const pngEast = project(279.8, 0).x;

  return (
    <div style={{position: 'absolute', inset: 0, opacity, pointerEvents: 'none'}}>
      <svg width={1920} height={1080} viewBox="0 0 1920 1080" style={{position: 'absolute', inset: 0}}>
        <defs>
          {anomalies.map((a, i) => {
            const c = a.kind === 'wet' ? '62,155,224' : '217,138,60';
            return (
              <radialGradient key={i} id={`anom-${i}`}>
                <stop offset="0%" stopColor={`rgba(${c},0.62)`} />
                <stop offset="55%" stopColor={`rgba(${c},0.30)`} />
                <stop offset="100%" stopColor={`rgba(${c},0)`} />
              </radialGradient>
            );
          })}
          <clipPath id="map-clip">
            <rect x={MAP.left} y={MAP.top} width={MAP.width} height={MAP.height} rx={10} />
          </clipPath>
        </defs>

        <g clipPath="url(#map-clip)">
          <rect
            x={MAP.left}
            y={MAP.top}
            width={MAP.width}
            height={MAP.height}
            fill="#050B13"
          />

          {/* graticule */}
          <g opacity={0.5 * baseReveal}>
            {[-40, -20, 20, 40].map((lat) => {
              const p = project(0, lat);
              return (
                <line
                  key={lat}
                  x1={MAP.left}
                  x2={MAP.left + MAP.width}
                  y1={p.y}
                  y2={p.y}
                  stroke={theme.grid}
                  strokeWidth={1}
                />
              );
            })}
            {Array.from({length: 12}).map((_, i) => {
              const lon = -20 + i * 30;
              const p = project(lon, 0);
              return (
                <line
                  key={lon}
                  x1={p.x}
                  x2={p.x}
                  y1={MAP.top}
                  y2={MAP.top + MAP.height}
                  stroke={theme.grid}
                  strokeWidth={1}
                />
              );
            })}
          </g>

          {/* land */}
          <g opacity={baseReveal}>
            {LAND.map((d, i) => (
              <g key={i} transform={`translate(${MAP.left} ${MAP.top}) scale(${SCALE})`}>
                <path d={d} fill={theme.land} stroke={theme.landEdge} strokeWidth={1.6} />
              </g>
            ))}
          </g>

          {/* lifted countries */}
          {highlight.map((h) => {
            const shape = COUNTRIES[h.iso];
            if (!shape || h.reveal <= 0.01) return null;
            return (
              <g key={h.iso} opacity={h.reveal}>
                <g transform={`translate(${MAP.left} ${MAP.top}) scale(${SCALE})`}>
                  <path
                    d={shape.d}
                    fill={`${h.color}3A`}
                    stroke={h.color}
                    strokeWidth={2.4}
                  />
                </g>
              </g>
            );
          })}

          {/* rainfall anomalies */}
          {anomalies.map((a, i) => {
            const p = project(a.lon, a.lat);
            const rev = a.reveal ?? 1;
            if (rev <= 0.01) return null;
            const rw = (a.rx / (WINDOW.lon1 - WINDOW.lon0)) * WORLD_W * SCALE;
            const rh = (a.ry / (WINDOW.lat1 - WINDOW.lat0)) * WORLD_H * SCALE;
            return (
              <ellipse
                key={i}
                cx={p.x}
                cy={p.y}
                rx={rw}
                ry={rh}
                fill={`url(#anom-${i})`}
                opacity={rev * (a.intensity ?? 1)}
              />
            );
          })}

          {/* equator and the unbroken fetch */}
          <g opacity={equatorReveal}>
            <line
              x1={MAP.left}
              x2={MAP.left + MAP.width}
              y1={equatorY}
              y2={equatorY}
              stroke="rgba(255,255,255,0.34)"
              strokeWidth={1.4}
              strokeDasharray="10 8"
            />
            <text
              x={MAP.left + 10}
              y={equatorY - 10}
              fill="rgba(255,255,255,0.4)"
              fontFamily={theme.mono}
              fontSize={15}
            >
              赤道 0°
            </text>
          </g>

          <g opacity={spanReveal}>
            <line
              x1={pngWest}
              x2={pngEast}
              y1={equatorY + 26}
              y2={equatorY + 26}
              stroke={theme.focus}
              strokeWidth={2.4}
              opacity={0.8}
            />
            {[pngWest, pngEast].map((x) => (
              <line
                key={x}
                x1={x}
                x2={x}
                y1={equatorY + 18}
                y2={equatorY + 34}
                stroke={theme.focus}
                strokeWidth={2.4}
                opacity={0.8}
              />
            ))}
            <text
              x={(pngWest + pngEast) / 2}
              y={equatorY + 50}
              textAnchor="middle"
              fill={theme.focus}
              fontFamily={theme.font}
              fontSize={20}
              fontWeight={700}
              letterSpacing={1}
            >
              162 个经度 · 18000 公里 · 没有陆地
            </text>
          </g>

          {/* ocean names */}
          <g opacity={baseReveal * 0.9}>
            {OCEAN_LABELS.map((l) => {
              const p = project(l.lon, l.lat);
              return (
                <text
                  key={l.text}
                  x={p.x}
                  y={p.y}
                  textAnchor="middle"
                  fill="rgba(150,180,210,0.22)"
                  fontFamily={theme.font}
                  fontSize={l.size}
                  fontWeight={700}
                  letterSpacing={3}
                >
                  {l.text}
                </text>
              );
            })}
          </g>

          {showContinentLabels ? (
            <g opacity={baseReveal * 0.75}>
              {CONTINENT_LABELS.map((l) => {
                const p = project(l.lon, l.lat);
                return (
                  <text
                    key={l.text}
                    x={p.x}
                    y={p.y}
                    textAnchor="middle"
                    fill="rgba(206,220,236,0.5)"
                    fontFamily={theme.font}
                    fontSize={l.size}
                    letterSpacing={1}
                  >
                    {l.text}
                  </text>
                );
              })}
            </g>
          ) : null}

          <rect
            x={MAP.left}
            y={MAP.top}
            width={MAP.width}
            height={MAP.height}
            fill="none"
            stroke={theme.panelEdge}
            strokeWidth={1}
            rx={10}
          />
        </g>
      </svg>

      {/* markers live outside the SVG so their text is not scaled by any transform */}
      {markers.map((m, i) => {
        const p = project(m.lon, m.lat);
        const rev = m.reveal ?? 1;
        if (rev <= 0.01) return null;
        const dir = m.side ?? 'up';
        const off = dir === 'up' ? -1 : 1;
        const labelY = dir === 'left' || dir === 'right' ? 0 : off * 30;
        return (
          <div
            key={i}
            style={{
              position: 'absolute',
              left: p.x,
              top: p.y,
              opacity: rev,
              transform: `scale(${0.85 + rev * 0.15})`,
              transformOrigin: 'center',
            }}
          >
            <div
              style={{
                position: 'absolute',
                left: -4,
                top: -4,
                width: 8,
                height: 8,
                borderRadius: 8,
                background: m.color,
                boxShadow: `0 0 12px ${m.color}`,
              }}
            />
            <div
              style={{
                position: 'absolute',
                ...(m.labelSide === 'left' ? {right: 14, textAlign: 'right' as const} : {left: 12}),
                top: labelY - 12,
                color: m.color,
                fontFamily: theme.font,
                fontSize: 18,
                fontWeight: 700,
                whiteSpace: 'nowrap',
                textShadow: '0 2px 10px rgba(0,0,0,0.95)',
              }}
            >
              {m.label}
              {m.sub ? (
                <span style={{color: theme.textDim, fontWeight: 400, marginLeft: 7, fontSize: 16}}>
                  {m.sub}
                </span>
              ) : null}
            </div>
          </div>
        );
      })}

      <rect x={0} y={0} width={1920} height={1080} fill="#03060B" opacity={dim * 0.6} />
    </div>
  );
};
