#!/usr/bin/env node
/**
 * Bake NOAA CPC's Oceanic Niño Index into a static TypeScript module.
 *
 * Source: .cache/enso/oni.ascii.txt, downloaded verbatim from
 *   https://www.cpc.ncep.noaa.gov/data/indices/oni.ascii.txt
 * (ERSSTv5, 3-month running mean of Niño-3.4 SST anomalies, 1991-2020 base.)
 *
 * The file lists overlapping 3-month seasons (DJF, JFM, ... NDJ) in calendar
 * order, so each row is really one *centred* month: DJF 1950 is centred on
 * January 1950. Reading them in file order therefore yields a clean monthly
 * series with no gaps and no overlap handling needed.
 *
 * Usage: node scripts/build-oni.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const PKG = path.resolve(HERE, '..');
const SRC = path.join(PKG, '.cache/enso/oni.ascii.txt');
const OUT = path.join(PKG, 'src/enso/oni.ts');
const URL = 'https://www.cpc.ncep.noaa.gov/data/indices/oni.ascii.txt';

const rows = fs
  .readFileSync(SRC, 'utf8')
  .split('\n')
  .slice(1)
  .map((l) => l.trim().split(/\s+/))
  .filter((c) => c.length === 4)
  .map(([seas, yr, total, anom]) => ({seas, yr: Number(yr), total: Number(total), anom: Number(anom)}));

if (rows.length < 900) throw new Error(`only ${rows.length} rows parsed`);

const startYear = rows[0].yr;
const values = rows.map((r) => r.anom);
const sst = rows.map((r) => r.total);

/*
 * A short integrity check: the row order must be strictly the 12 season codes
 * cycling, otherwise the "one row = one month" assumption is wrong and every
 * date in the film would silently shift.
 */
const SEASONS = ['DJF','JFM','FMA','MAM','AMJ','MJJ','JJA','JAS','ASO','SON','OND','NDJ'];
rows.forEach((r, i) => {
  const expected = SEASONS[i % 12];
  if (r.seas !== expected) throw new Error(`row ${i}: expected ${expected}, got ${r.seas}`);
  const expectedYear = startYear + Math.floor(i / 12);
  if (r.yr !== expectedYear) throw new Error(`row ${i}: expected year ${expectedYear}, got ${r.yr}`);
  if (!Number.isFinite(r.anom)) throw new Error(`row ${i}: bad anomaly`);
});

const fmt = (arr) => {
  const out = [];
  for (let i = 0; i < arr.length; i += 12) {
    out.push('  ' + arr.slice(i, i + 12).map((v) => v.toFixed(2)).join(', ') + ',');
  }
  return out.join('\n');
};

const text = `/*
 * Generated by scripts/build-oni.mjs — do not edit by hand.
 *
 * Oceanic Niño Index (ONI): 3-month running mean of ERSSTv5 sea-surface
 * temperature anomalies in the Niño-3.4 region (5°N-5°S, 120°W-170°W),
 * relative to the 1991-2020 base period. Values are indexed by the CENTRE
 * month of each 3-month window, which is why the series is a clean monthly
 * sequence with no overlap.
 *
 * Source: NOAA Climate Prediction Center, ${URL}
 * Fetched into .cache/enso/oni.ascii.txt, ${rows.length} rows,
 * ${rows[0].seas} ${startYear} through ${rows[rows.length - 1].seas} ${rows[rows.length - 1].yr}.
 *
 * The five-month threshold that defines an event is |ONI| >= 0.5 sustained;
 * a "strong" event reaches |ONI| >= 1.5 and a "very strong" event >= 2.0.
 */

/** Calendar year of the first sample (January). */
export const ONI_START_YEAR = ${startYear};

/** Number of monthly samples. */
export const ONI_MONTHS = ${values.length};

/** ONI anomaly, in °C, indexed by month since January ${startYear}. */
export const ONI: number[] = [
${fmt(values)}
];

/** Concurrent Niño-3.4 sea-surface temperature itself, in °C. */
export const NINO34_SST: number[] = [
${fmt(sst)}
];

/** Month index (since January ${startYear}) -> decimal year, e.g. 1972.5. */
export const monthToYear = (m: number): number => ${startYear} + m / 12;

/** Month index -> {year, month} with month in 1..12. */
export const monthToCalendar = (m: number): {year: number; month: number} => ({
  year: ${startYear} + Math.floor(m / 12),
  month: (m % 12) + 1,
});

/** Calendar date -> month index, clamped to the available record. */
export const atYearMonth = (year: number, month = 1): number =>
  Math.max(0, Math.min(${values.length - 1}, (year - ${startYear}) * 12 + (month - 1)));

/** The largest |ONI| inside a month range — how strong an event actually got. */
export const peakAbs = (from: number, to: number): number => {
  let peak = 0;
  for (let m = Math.max(0, from); m <= Math.min(${values.length - 1}, to); m++) {
    if (Math.abs(ONI[m]) > Math.abs(peak)) peak = ONI[m];
  }
  return peak;
};

/** The signed peak (keeps the sign, so El Niño stays positive). */
export const peakOf = peakAbs;
`;

fs.writeFileSync(OUT, text, 'utf8');
console.log(`ONI ${rows.length} months, ${rows[0].seas} ${startYear} .. ${rows[rows.length-1].seas} ${rows[rows.length-1].yr}`);
console.log(`wrote ${path.relative(PKG, OUT)} (${(fs.statSync(OUT).size/1024).toFixed(1)} KB)`);
